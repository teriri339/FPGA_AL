"""Convert the supplied lab_ex3 Anlogic ROM to a compact display-only ROM.

This preserves the existing logo artwork, crops unused vertical whitespace,
and quantizes its antialiasing to 16 colours on white. Emit an apply_patch patch
for the generated RTL; optional preview/vectors go into a new temporary folder.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

import numpy as np
from PIL import Image


def convert(source):
    raw = Path(source).read_bytes()
    words = re.findall(r"15'd(\d+):\s*O_pixel\s*=\s*25'h([0-9a-fA-F]+)", raw.decode())
    if not words:
        raise ValueError("Not a recognised 160x160 lab_ex3 logo ROM")
    canvas = np.full((160, 160, 3), 255, dtype=np.uint8)
    for address, value in words:
        address, value = int(address), int(value, 16)
        if address >= 160 * 160:
            raise ValueError("Logo address outside original 160x160 image")
        if value & (1 << 24):
            canvas[address // 160, address % 160] = [(value >> 16) & 255, (value >> 8) & 255, value & 255]
    image = Image.fromarray(canvas[32:128])
    quantized = image.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    entries = np.array(quantized.getpalette()[:48], dtype=np.uint8).reshape(-1, 3)
    palette = np.full((16, 3), 255, dtype=np.uint8)
    palette[:len(entries)] = entries
    indices = np.array(quantized, dtype=np.uint8)
    white_index = int(np.argmin(np.square(palette.astype(float) - 255).sum(axis=1)))
    rom = np.full(16384, white_index, dtype=np.uint8)
    rom[:160 * 96] = indices.ravel()
    metadata = {"source_sha256": hashlib.sha256(raw).hexdigest(), "original_size": [160, 160],
                "crop_xywh": [0, 32, 160, 96], "rom_depth": 16384, "index_bits": 4,
                "palette_rgb": palette.tolist(), "source_entries": len(words)}
    return rom, palette, metadata


def render_rtl(rom, palette, metadata):
    lines = ["`timescale 1ns/1ps",
             "// Generated by tools/prepare_anlogic_logo.py from supplied lab_ex3 artwork.",
             "// Source SHA256: " + metadata["source_sha256"],
             "// 160x96 crop, 16-colour antialiasing on white; no external readmemh path.",
             "module hx_anlogic_logo_rom (", "    input wire I_clk, I_rst_n,",
             "    input wire [13:0] I_addr,", "    output reg [23:0] O_rgb", ") ;",
             "    localparam [65535:0] PIXELS = {"]
    # Highest address first; nibble 0 in the packed constant is ROM entry 0.
    for end in range(16384, 0, -64):
        value = "".join(format(int(n), "x") for n in rom[end - 64:end][::-1])
        lines.append("        256'h" + value + ("," if end > 64 else ""))
    lines += ["    };", "    reg [3:0] pixels [0:16383];", "    reg [3:0] index_q;", "    integer n;",
              "    initial begin", "        for (n=0; n<16384; n=n+1) pixels[n] = PIXELS[n*4 +: 4];", "    end",
              "    always @(posedge I_clk or negedge I_rst_n) begin", "        if (!I_rst_n) index_q <= 0;",
              "        else index_q <= pixels[I_addr];", "    end", "    always @(*) begin", "        case (index_q)"]
    for i, (r, g, b) in enumerate(palette):
        lines.append(f"            4'd{i}: O_rgb = 24'h{r:02x}{g:02x}{b:02x};")
    lines += ["            default: O_rgb = 24'hffffff;", "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--vectors", type=Path)
    parser.add_argument("--emit-patch", action="store_true")
    args = parser.parse_args()
    rom, palette, metadata = convert(args.source)
    if args.vectors:
        args.vectors.mkdir(parents=True, exist_ok=False)
        rgb = palette[rom].astype(np.uint32)
        expected = (rgb[:, 0] << 16) | (rgb[:, 1] << 8) | rgb[:, 2]
        np.savetxt(args.vectors / "logo_expected.mem", expected, fmt="%06x")
        Image.fromarray(palette[rom[:15360]].reshape(96, 160, 3)).save(args.vectors / "logo_preview.png")
        (args.vectors / "logo_source.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    if args.emit_patch:
        destination = Path(__file__).resolve().parents[1] / "reference_edge_project/user_source/hdl_source/hx1p35_port/hx_anlogic_logo_rom.v"
        print("*** Begin Patch\n*** Add File: " + destination.as_posix())
        print("\n".join("+" + line for line in render_rtl(rom, palette, metadata).splitlines()))
        print("*** End Patch")
    else:
        print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
